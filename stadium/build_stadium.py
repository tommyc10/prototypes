def grass_material():
    """Two greens in mowing stripes, with noise so it doesn't look flat."""
    mat = bpy.data.materials.new("Grass")
    nt = mat.node_tree
    bsdf = principled(mat)
    bsdf.inputs["Roughness"].default_value = 1.0
    bsdf.inputs["Specular IOR Level"].default_value = 0.15   # grass barely shines
    n = nt.nodes
    coord = n.new("ShaderNodeTexCoord")
    sep = n.new("ShaderNodeSeparateXYZ")
    div = n.new("ShaderNodeMath"); div.operation = "DIVIDE"
    div.inputs[1].default_value = PITCH_L / 18          # 18 stripes across the pitch
    flo = n.new("ShaderNodeMath"); flo.operation = "FLOOR"
    mod = n.new("ShaderNodeMath"); mod.operation = "FLOORED_MODULO"
    mod.inputs[1].default_value = 2.0
    ramp = n.new("ShaderNodeValToRGB")
    ramp.color_ramp.interpolation = "CONSTANT"
    ramp.color_ramp.elements[0].color = (*GRASS_A, 1)
    ramp.color_ramp.elements[1].position = 0.5
    ramp.color_ramp.elements[1].color = (*GRASS_B, 1)
    noise = n.new("ShaderNodeTexNoise")
    noise.inputs["Scale"].default_value = 0.6
    noise.inputs["Detail"].default_value = 8.0
    vary = n.new("ShaderNodeMath"); vary.operation = "MULTIPLY_ADD"
    vary.inputs[1].default_value = 0.45
    vary.inputs[2].default_value = 0.78
    scale = n.new("ShaderNodeVectorMath"); scale.operation = "SCALE"
    fine = n.new("ShaderNodeTexNoise")
    fine.inputs["Scale"].default_value = 60.0
    bump = n.new("ShaderNodeBump")
    bump.inputs["Strength"].default_value = 0.15
    L = nt.links.new
    L(coord.outputs["Object"], sep.inputs[0])
    L(sep.outputs["X"], div.inputs[0])
    L(div.outputs[0], flo.inputs[0])
    L(flo.outputs[0], mod.inputs[0])
    L(mod.outputs[0], ramp.inputs[0])
    L(coord.outputs["Object"], noise.inputs["Vector"])
    L(noise.outputs["Fac"], vary.inputs[0])
    L(ramp.outputs["Color"], scale.inputs[0])
    L(vary.outputs[0], scale.inputs["Scale"])
    L(scale.outputs["Vector"], bsdf.inputs["Base Color"])
    L(coord.outputs["Object"], fine.inputs["Vector"])
    L(fine.outputs["Fac"], bump.inputs["Height"])
    L(bump.outputs["Normal"], bsdf.inputs["Normal"])
    return mat


def city_material():
    """Dark facades with randomly lit windows. Walls are cut into a grid of
    window cells; each cell gets a random number, and only some light up.
    Roofs (faces pointing up) get no windows."""
    mat = bpy.data.materials.new("City")
    nt = mat.node_tree
    bsdf = principled(mat)
    bsdf.inputs["Base Color"].default_value = (0.03, 0.026, 0.024, 1)
    bsdf.inputs["Roughness"].default_value = 0.8
    bsdf.inputs["Emission Color"].default_value = (1.0, 0.62, 0.30, 1)
    n, L = nt.nodes, nt.links.new

    def math(op, a=None, b=None, c=None):
        node = n.new("ShaderNodeMath"); node.operation = op
        for i, v in enumerate((a, b, c)):
            if isinstance(v, (int, float)):
                node.inputs[i].default_value = v
            elif v is not None:
                L(v, node.inputs[i])
        return node.outputs[0]

    geo = n.new("ShaderNodeNewGeometry")
    pos = n.new("ShaderNodeSeparateXYZ"); L(geo.outputs["Position"], pos.inputs[0])
    nrm = n.new("ShaderNodeSeparateXYZ"); L(geo.outputs["Normal"], nrm.inputs[0])
    u = math("DIVIDE", math("ADD", pos.outputs["X"], pos.outputs["Y"]), 3.6)  # 3.6 m bays
    v = math("DIVIDE", pos.outputs["Z"], 3.2)                                  # 3.2 m floors
    cell = n.new("ShaderNodeCombineXYZ")
    L(math("FLOOR", u), cell.inputs["X"]); L(math("FLOOR", v), cell.inputs["Y"])
    rnd = n.new("ShaderNodeTexWhiteNoise"); rnd.noise_dimensions = "3D"
    L(cell.outputs[0], rnd.inputs["Vector"])
    lit = math("GREATER_THAN", rnd.outputs["Value"], 0.62)          # ~38% of windows lit
    win_u = math("LESS_THAN", math("ABSOLUTE", math("SUBTRACT", math("FRACT", u), 0.5)), 0.3)
    win_v = math("LESS_THAN", math("ABSOLUTE", math("SUBTRACT", math("FRACT", v), 0.5)), 0.22)
    wall = math("LESS_THAN", math("ABSOLUTE", nrm.outputs["Z"]), 0.5)
    mask = math("MULTIPLY", math("MULTIPLY", lit, win_u), math("MULTIPLY", win_v, wall))
    # vary brightness a little per window so it doesn't look printed
    L(math("MULTIPLY", mask, math("MULTIPLY_ADD", rnd.outputs["Value"], 6.0, 1.0)),
      bsdf.inputs["Emission Strength"])
    return mat


def roof_material():
    """Metal roof with panel seams, so it doesn't read as a flat slab."""
    mat = material("Roof", ROOF, rough=0.45, metal=0.6)
    nt = mat.node_tree
    wave = nt.nodes.new("ShaderNodeTexWave")
    wave.inputs["Scale"].default_value = 0.08
    wave.inputs["Distortion"].default_value = 0.0
    wave.bands_direction = "X"
    coord = nt.nodes.new("ShaderNodeTexCoord")
    bump = nt.nodes.new("ShaderNodeBump")
    bump.inputs["Strength"].default_value = 0.4
    ramp = nt.nodes.new("ShaderNodeValToRGB")
    ramp.color_ramp.elements[0].color = (ROOF[0] * 0.6, ROOF[1] * 0.6, ROOF[2] * 0.6, 1)
    ramp.color_ramp.elements[1].color = (ROOF[0] * 1.6, ROOF[1] * 1.6, ROOF[2] * 1.6, 1)
    nt.links.new(coord.outputs["Object"], wave.inputs["Vector"])
    nt.links.new(wave.outputs["Fac"], bump.inputs["Height"])
    nt.links.new(wave.outputs["Fac"], ramp.inputs[0])
    nt.links.new(ramp.outputs["Color"], principled(mat).inputs["Base Color"])
    nt.links.new(bump.outputs["Normal"], principled(mat).inputs["Normal"])
    return mat


