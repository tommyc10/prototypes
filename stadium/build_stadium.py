def tier_layout(spec, d0):
    """Where each tier starts and ends (d = distance back from the pitch edge)."""
    tiers, d, h = [], d0, 1.2
    for k, (rows, rise) in enumerate(spec):
        if k > 0:
            prev = tiers[-1]
            d = prev["end_d"] - 6.0          # overhang the tier below
            h = prev["end_h"] + 4.5          # concourse / boxes between tiers
        tiers.append(dict(rows=rows, rise=rise, d=d, h=h,
                          end_d=d + rows * ROW_D, end_h=h + rows * rise))
    return tiers


def seat_mesh():
    """One stadium seat: a pan and a backrest. Instanced ~35,000 times."""
    verts, faces = [], []
    for c, sz in (((0, -0.02, 0.42), (0.44, 0.40, 0.05)),
                  ((0, -0.21, 0.66), (0.44, 0.05, 0.46))):
        v, f = box_geo(*c, *sz, len(verts))
        verts += v; faces += f
    me = bpy.data.meshes.new("Seat")
    me.from_pydata(verts, [], faces)
    me.update()
    return me


def build_stand(spec, mats, seat):
    side = spec["side"]
    is_long = side in ("E", "W")
    d0 = SIDE_GAP if is_long else END_GAP
    length = (PITCH_L + 2 * END_GAP) if is_long else (PITCH_W + 2 * SIDE_GAP)
    tiers = tier_layout(spec["tiers"], d0)
    back = max(t["end_d"] for t in tiers) + 1.5
    roof_h = tiers[-1]["end_h"] + 4.0

    # An empty at the pitch edge; every part of the stand hangs off it, built
    # facing +Y. Rotating the empty turns the stand to face the pitch.
    anchor = bpy.data.objects.new(spec["name"], None)
    link(anchor)
    place = {"E": ((0, -PITCH_W / 2, 0), 0.0),
             "W": ((0, PITCH_W / 2, 0), math.pi),
             "N": ((PITCH_L / 2, 0, 0), math.pi / 2),
             "S": ((-PITCH_L / 2, 0, 0), -math.pi / 2)}[side]
    anchor.location = place[0]
    anchor.rotation_euler = (0, 0, place[1])

    bitmap = text_bitmap(SEAT_TEXT) if spec.get("text_tier") is not None else None
    blue_pts, white_pts = [], []

    for k, t in enumerate(tiers):
        d, h, rows, rise = t["d"], t["h"], t["rows"], t["rise"]
        # Stepped outline: front, then tread/riser for each row, then back.
        prof = [(-d, 0.0 if k == 0 else h - 2.5), (-d, h)]
        for r in range(rows):
            z = h + r * rise
            prof.append((-(d + (r + 1) * ROW_D), z))
            prof.append((-(d + (r + 1) * ROW_D), z + rise))
        prof.append((-t["end_d"], t["end_h"] + 1.1))          # parapet at the back
        if k == 0:
            prof.append((-(t["end_d"] + 0.3), t["end_h"] + 1.1))
            prof.append((-(t["end_d"] + 0.3), 0.0))
        else:
            prof.append((-(t["end_d"] + 0.3), t["end_h"] + 1.1))
            prof.append((-(t["end_d"] + 0.3), t["end_h"] - 3.0))  # sloped underside
        extrude_profile(f"{spec['name']} tier {k + 1}", prof, length, mats["concrete"], anchor)

        # Fascia band along the front of upper tiers.
        if k > 0:
            box(f"{spec['name']} fascia {k}", (0, -d + 0.05, h - 1.3), (length, 0.15, 2.4),
                mats["fascia"], anchor)
            # Wall at the back of the tier below, closing the gap under the overhang.
            below = tiers[k - 1]
            under_z = (h - 2.5) + (below["end_d"] - d) / ROW_D * rise
            wall_h = under_z - below["end_h"]
            box(f"{spec['name']} concourse {k}",
                (0, -(below["end_d"] + 0.6), below["end_h"] + wall_h / 2),
                (length, 0.6, wall_h), mats["concourse"], anchor)

        # Seats: one point per seat, aisles left empty.
        usable = length - 4.0
        cols = int(usable / SEAT_W)
        x0 = -usable / 2
        text_rows = None
        if bitmap is not None and k == spec["text_tier"]:
            tw = len(bitmap[0])
            pw = min(1.0, (usable - 6) / tw)                    # letter pixel width (m)
            sy = max(1, min((rows - 2) // 7, round(pw * 1.2 / math.hypot(ROW_D, rise))))
            r0 = (rows - 7 * sy) // 2
            tx0 = -tw * pw / 2
            text_rows = (r0, sy, pw, tx0, tw)
        for r in range(rows):
            y = -(d + r * ROW_D + 0.45)
            z = h + r * rise
            for c in range(cols):
                if c % (AISLE_EVERY + 2) >= AISLE_EVERY:
                    continue                                    # aisle
                x = x0 + (c + 0.5) * SEAT_W
                white = False
                if text_rows is not None:
                    r0, sy, pw, tx0, tw = text_rows
                    if r0 <= r < r0 + 7 * sy:
                        # Seen from the pitch, +x is on the viewer's left,
                        # so read the letters from -x to stop them mirroring.
                        col = int((-x - tx0) // pw)
                        prow = 6 - (r - r0) // sy
                        white = 0 <= col < tw and bitmap[prow][col] == "1"
                (white_pts if white else blue_pts).append((x, y, z))

    instancer(f"{spec['name']} seats", blue_pts, seat, mats["seat_blue"], anchor)
    if white_pts:
        instancer(f"{spec['name']} seats white", white_pts, seat, mats["seat_white"], anchor)

    # Outer wall and roof.
    box(f"{spec['name']} cladding", (0, -(back + 0.75), roof_h / 2), (length, 1.5, roof_h),
        mats["cladding"], anchor)
    box(f"{spec['name']} blue band", (0, -(back + 1.55), roof_h - 1.2), (length, 0.1, 1.2),
        mats["band"], anchor)
    roof_front = d0 + 2.0
    extrude_profile(f"{spec['name']} roof",
                    [(-roof_front, roof_h), (-roof_front, roof_h + 2.2),
                     (-(back + 1.5), roof_h + 3.2), (-(back + 1.5), roof_h)],
                    length + 2, mats["roof"], anchor)
    box(f"{spec['name']} roof truss", (0, -(roof_front + 0.6), roof_h + 0.9), (length + 2, 1.2, 3.0),
        mats["steel"], anchor)

    # Floodlights: glowing panels along the roof edge, plus real spot lights
    # aimed at the pitch. Their own material so each stand can switch on alone.
    flood = material(f"{spec['name']} floodlight", (1, 1, 1), emit=FLOOD_WARM, strength=0.0)
    n_panels = int(length / 4.2)
    verts, faces = [], []
    for i in range(n_panels):
        x = -length / 2 + (i + 0.5) * length / n_panels
        v, f = box_geo(x, -(roof_front - 0.1), roof_h - 0.4, 1.8, 0.25, 0.7, len(verts))
        verts += v; faces += f
    panels = mesh_obj(f"{spec['name']} floodlight panels", verts, faces, flood, anchor)
    fix_normals(panels)

    spots = []
    n_spots = 7 if is_long else 5
    reach = PITCH_W / 2 if is_long else PITCH_L / 2
    for i in range(n_spots):
        x = -length / 2 + (i + 0.5) * length / n_spots
        light = bpy.data.lights.new(f"{spec['name']} flood {i}", "SPOT")
        light.spot_size = math.radians(85)
        light.spot_blend = 0.6
        light.shadow_soft_size = 1.5
        light.color = FLOOD_WARM
        light.energy = 0.0
        obj = link(bpy.data.objects.new(light.name, light), anchor)
        obj.location = (x, -(roof_front - 0.5), roof_h - 0.6)
        target = Vector((x * 0.55, reach * 0.85, 0)) - Vector(obj.location)
        obj.rotation_euler = target.to_track_quat("-Z", "Y").to_euler()
        spots.append(light)

    # Advertising boards between the pitch and the front row.
    box(f"{spec['name']} boards", (0, -(d0 - 3.0), 0.45), (length - 12, 0.12, 0.9),
        mats["boards"], anchor)

    return dict(anchor=anchor, flood=flood, spots=spots, length=length,
                back=back, roof_h=roof_h, seats=len(blue_pts) + len(white_pts))


def build_corners(stands, mats):
    """Fill the four corners so the bowl feels enclosed."""
    by_side = {s["side"]: b for s, b in zip(STANDS, stands)}
    for sx in (-1, 1):
        for sy in (-1, 1):
            end = by_side["N" if sx > 0 else "S"]
            side = by_side["W" if sy > 0 else "E"]
            x0, y0 = PITCH_L / 2 + END_GAP, PITCH_W / 2 + SIDE_GAP
            x1, y1 = PITCH_L / 2 + end["back"] + 1.5, PITCH_W / 2 + side["back"] + 1.5
            hgt = min(end["roof_h"], side["roof_h"]) - 4
            box("Corner", (sx * (x0 + x1) / 2, sy * (y0 + y1) / 2, hgt / 2),
                (x1 - x0, y1 - y0, hgt), mats["city"])


