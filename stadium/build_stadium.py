# Surroundings: a night-time city grid with street lights.
# --------------------------------------------------------------------------
def build_city(mats, rng):
    ground = mesh_obj("Ground", [(-6000, -6000, -0.02), (6000, -6000, -0.02),
                                 (6000, 6000, -0.02), (-6000, 6000, -0.02)],
                      [(0, 1, 2, 3)], mats["asphalt"])
    ground.data.polygons[0].use_smooth = True

    clear_x, clear_y = PITCH_L / 2 + 60, PITCH_W / 2 + 65   # stadium footprint + forecourt
    block, road = 34.0, 12.0
    pitch_ = block + road
    verts, faces, lamps = [], [], []
    n = int(700 / pitch_)
    for i in range(-n, n + 1):
        for j in range(-n, n + 1):
            cx, cy = i * pitch_, j * pitch_
            if math.hypot(cx, cy) > 700:
                continue
            inside = abs(cx) < clear_x + block / 2 and abs(cy) < clear_y + block / 2
            if inside:
                continue
            # street lights along the road on two sides of each block
            for t in range(3):
                lamps.append((cx - pitch_ / 2 + t * pitch_ / 3, cy - pitch_ / 2, 6.0))
                lamps.append((cx - pitch_ / 2, cy - pitch_ / 2 + t * pitch_ / 3, 6.0))
            # a few terraced buildings per block, some taller blocks of flats
            parts = rng.choice((2, 3, 4))
            for p in range(parts):
                w = block / parts
                bx = cx - block / 2 + (p + 0.5) * w
                tall = rng.random() < 0.05
                hgt = rng.uniform(30, 70) if tall else rng.uniform(9, 17)
                dep = block * rng.uniform(0.55, 0.95)
                v, f = box_geo(bx, cy, hgt / 2, w * 0.96, dep, hgt, len(verts))
                verts += v; faces += f
    # A hotel block beside the Shed End, like the real ground.
    for (bx, by, sx, sy, hgt) in ((-125, -40, 40, 30, 32), (-125, 20, 30, 40, 24)):
        v, f = box_geo(bx, by, hgt / 2, sx, sy, hgt, len(verts))
        verts += v; faces += f
    city = mesh_obj("City", verts, faces, mats["city"])
    fix_normals(city)

    bm = bmesh.new()
    bmesh.ops.create_icosphere(bm, subdivisions=1, radius=0.5)
    lamp_mesh = bpy.data.meshes.new("Street light")
    bm.to_mesh(lamp_mesh); bm.free()
    lamp_mesh.materials.append(mats["streetlight"])
    cloud = mesh_obj("Street lights", lamps, [])
    cloud.instance_type = "VERTS"
    link(bpy.data.objects.new("Street light", lamp_mesh), cloud)


