def build_pitch(mats):
    grass_l = PITCH_L + 2 * END_GAP
    grass_w = PITCH_W + 2 * SIDE_GAP
    g = mesh_obj("Pitch", [(-grass_l / 2, -grass_w / 2, 0), (grass_l / 2, -grass_w / 2, 0),
                           (grass_l / 2, grass_w / 2, 0), (-grass_l / 2, grass_w / 2, 0)],
                 [(0, 1, 2, 3)], mats["grass"])
    g.data.polygons[0].use_smooth = True

    # Pitch markings, collected into one mesh of thin quads.
    verts, faces = [], []
    w, z = 0.12, 0.01

    def line(x1, y1, x2, y2):
        d = Vector((x2 - x1, y2 - y1, 0)).normalized()
        nx, ny = -d.y * w / 2, d.x * w / 2
        i = len(verts)
        verts.extend([(x1 + nx, y1 + ny, z), (x2 + nx, y2 + ny, z),
                      (x2 - nx, y2 - ny, z), (x1 - nx, y1 - ny, z)])
        faces.append((i, i + 1, i + 2, i + 3))

    def arc(cx, cy, r, a0, a1, width=w, seg=64):
        i0 = len(verts)
        steps = max(4, int(seg * abs(a1 - a0) / (2 * math.pi)))
        for k in range(steps + 1):
            a = a0 + (a1 - a0) * k / steps
            for rr in (r - width / 2, r + width / 2):
                verts.append((cx + rr * math.cos(a), cy + rr * math.sin(a), z))
        for k in range(steps):
            a = i0 + 2 * k
            faces.append((a, a + 2, a + 3, a + 1))

    hl, hw = PITCH_L / 2, PITCH_W / 2
    line(-hl, -hw, hl, -hw); line(hl, -hw, hl, hw)
    line(hl, hw, -hl, hw); line(-hl, hw, -hl, -hw)
    line(0, -hw, 0, hw)
    arc(0, 0, 9.15, 0, 2 * math.pi)
    arc(0, 0, 0.08, 0, 2 * math.pi, width=0.16, seg=16)
    for s in (-1, 1):
        gx = s * hl
        for depth, half in ((16.5, 20.16), (5.5, 9.16)):       # penalty box, six-yard box
            line(gx, -half, gx - s * depth, -half)
            line(gx - s * depth, -half, gx - s * depth, half)
            line(gx - s * depth, half, gx, half)
        spot = gx - s * 11.0
        arc(spot, 0, 0.08, 0, 2 * math.pi, width=0.16, seg=16)
        a = math.acos(5.5 / 9.15)
        base = math.pi if s > 0 else 0.0
        arc(spot, 0, 9.15, base - a, base + a)               # the "D"
        for cy in (-1, 1):                                     # corner arcs
            start = math.atan2(-cy, -s)
            arc(gx, cy * hw, 1.0, start - math.pi / 4, start + math.pi / 4, seg=32)
    mesh_obj("Pitch markings", verts, faces, mats["line"])

    # Goals with nets.
    for s in (-1, 1):
        gx = s * hl
        verts, faces = [], []
        for y in (-3.66, 3.66):
            v, f = box_geo(gx + s * 0.06, y, 1.22, 0.12, 0.12, 2.44, len(verts))
            verts += v; faces += f
        v, f = box_geo(gx + s * 0.06, 0, 2.38, 0.12, 7.44, 0.12, len(verts))
        verts += v; faces += f
        goal = mesh_obj("Goal", verts, faces, mats["line"])
        fix_normals(goal)
        build_net(gx, s, mats["net"])


def build_net(gx, s, mat):
    """A goal net: a subdivided box shell turned into strings by a modifier."""
    depth, top_depth = 2.0, 1.0
    p = [(gx + s * 0.1, -3.66, 0), (gx + s * depth, -3.66, 0), (gx + s * depth, 3.66, 0),
         (gx + s * 0.1, 3.66, 0), (gx + s * 0.1, -3.66, 2.44), (gx + s * top_depth, -3.66, 2.44),
         (gx + s * top_depth, 3.66, 2.44), (gx + s * 0.1, 3.66, 2.44)]
    faces = [(1, 2, 6, 5), (4, 5, 6, 7), (0, 1, 5, 4), (3, 7, 6, 2)]
    net = mesh_obj("Net", p, faces, mat)
    bm = bmesh.new(); bm.from_mesh(net.data)
    bmesh.ops.subdivide_edges(bm, edges=bm.edges, cuts=24, use_grid_fill=True)
    bm.to_mesh(net.data); bm.free()
    mod = net.modifiers.new("strings", "WIREFRAME")
    mod.thickness = 0.015
    return net


