def clear_scene():
    """Remove everything so the script can be re-run in a clean scene."""
    for collection in (bpy.data.objects, bpy.data.meshes, bpy.data.materials,
                       bpy.data.lights, bpy.data.cameras, bpy.data.node_groups,
                       bpy.data.worlds, bpy.data.actions):
        for block in list(collection):
            collection.remove(block)


def link(obj, parent=None):
    bpy.context.scene.collection.objects.link(obj)
    if parent is not None:
        obj.parent = parent
    return obj


def mesh_obj(name, verts, faces, mat=None, parent=None, smooth=False):
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, [], faces)
    me.validate()
    me.update()
    if smooth:
        for poly in me.polygons:
            poly.use_smooth = True
    if mat is not None:
        me.materials.append(mat)
    return link(bpy.data.objects.new(name, me), parent)


def fix_normals(obj):
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(obj.data)
    bm.free()


def box_geo(cx, cy, cz, sx, sy, sz, offset=0):
    """Vertices and faces of an axis-aligned box centred on (cx, cy, cz)."""
    hx, hy, hz = sx / 2, sy / 2, sz / 2
    v = [(cx + x * hx, cy + y * hy, cz + z * hz)
         for x in (-1, 1) for y in (-1, 1) for z in (-1, 1)]
    f = [(0, 1, 3, 2), (4, 6, 7, 5), (0, 4, 5, 1), (2, 3, 7, 6), (0, 2, 6, 4), (1, 5, 7, 3)]
    return v, [tuple(i + offset for i in face) for face in f]


def box(name, center, size, mat, parent=None):
    v, f = box_geo(*center, *size)
    obj = mesh_obj(name, v, f, mat, parent)
    fix_normals(obj)
    return obj


def extrude_profile(name, profile, length, mat, parent=None):
    """Sweep a 2D (y, z) outline along X to make a solid, e.g. a stepped tier."""
    n = len(profile)
    verts = [(x, y, z) for x in (-length / 2, length / 2) for (y, z) in profile]
    faces = [(i, (i + 1) % n, n + (i + 1) % n, n + i) for i in range(n)]
    faces.append(tuple(reversed(range(n))))
    faces.append(tuple(range(n, 2 * n)))
    obj = mesh_obj(name, verts, faces, mat, parent)
    fix_normals(obj)
    return obj


def instancer(name, points, child_mesh, mat, parent=None):
    """One vertex per point; Blender draws `child_mesh` at every vertex.
    This is how ~32,000 seats stay cheap: one seat mesh, many copies."""
    cloud = mesh_obj(name, points, [], None, parent)
    cloud.instance_type = "VERTS"
    child = link(bpy.data.objects.new(name + " (instance)", child_mesh), cloud)
    if mat is not None:
        if len(child_mesh.materials) == 0:
            child_mesh.materials.append(None)
        child.material_slots[0].link = "OBJECT"   # colour per object, mesh shared
        child.material_slots[0].material = mat
    return cloud


def principled(mat):
    return next(n for n in mat.node_tree.nodes if n.type == "BSDF_PRINCIPLED")


def material(name, color, rough=0.5, metal=0.0, emit=None, strength=0.0):
    mat = bpy.data.materials.new(name)
    bsdf = principled(mat)
    bsdf.inputs["Base Color"].default_value = (*color, 1)
    bsdf.inputs["Roughness"].default_value = rough
    bsdf.inputs["Metallic"].default_value = metal
    if emit is not None:
        bsdf.inputs["Emission Color"].default_value = (*emit, 1)
        bsdf.inputs["Emission Strength"].default_value = strength
    return mat


def key_constant(datablock, path, frame, value):
    """Insert a keyframe that holds its value (a hard on/off switch)."""
    setattr(datablock, path, value)
    datablock.keyframe_insert(data_path=path, frame=frame)


def make_constant(idblock):
    """Switch every keyframe on an ID (light, node tree...) to CONSTANT, so
    values jump instead of fading. Blender 4.4+ keeps keys in 'channelbags'."""
    anim = idblock.animation_data
    if anim is None or anim.action is None:
        return
    try:
        from bpy_extras.anim_utils import action_get_channelbag_for_slot
        fcurves = action_get_channelbag_for_slot(anim.action, anim.action_slot).fcurves
    except ImportError:                       # older Blender
        fcurves = anim.action.fcurves
    for fc in fcurves:
        for kp in fc.keyframe_points:
            kp.interpolation = "CONSTANT"


