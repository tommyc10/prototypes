# World, camera, animation, render settings
# --------------------------------------------------------------------------
def build_world(haze):
    world = bpy.data.worlds.new("Night")
    bpy.context.scene.world = world
    nt = world.node_tree
    bg = next(n for n in nt.nodes if n.type == "BACKGROUND")
    # A dusk gradient: deep navy overhead, a little warmth at the horizon.
    coord = nt.nodes.new("ShaderNodeTexCoord")
    sep = nt.nodes.new("ShaderNodeSeparateXYZ")
    ramp = nt.nodes.new("ShaderNodeValToRGB")
    ramp.color_ramp.elements[0].position = 0.0
    ramp.color_ramp.elements[0].color = (0.06, 0.035, 0.03, 1)
    ramp.color_ramp.elements[1].position = 0.35
    ramp.color_ramp.elements[1].color = (0.004, 0.008, 0.025, 1)
    nt.links.new(coord.outputs["Generated"], sep.inputs[0])
    nt.links.new(sep.outputs["Z"], ramp.inputs[0])
    nt.links.new(ramp.outputs["Color"], bg.inputs["Color"])
    bg.inputs["Strength"].default_value = 1.0
    if haze:
        # A thin fog everywhere: this is what makes floodlight beams visible.
        vol = nt.nodes.new("ShaderNodeVolumePrincipled")
        vol.inputs["Density"].default_value = 0.0004
        vol.inputs["Anisotropy"].default_value = 0.4
        out = next(n for n in nt.nodes if n.type == "OUTPUT_WORLD")
        nt.links.new(vol.outputs[0], out.inputs["Volume"])


