def text_bitmap(text):
    """Turn text into 7 rows of '0'/'1' strings (row 0 = top of the letters)."""
    rows = [""] * 7
    for ch in text.upper():
        glyph = FONT.get(ch, FONT[" "])
        for r in range(7):
            rows[r] += glyph[r] + "0"
    return [r[:-1] for r in rows]


