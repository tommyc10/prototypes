def build_camera():
    scene = bpy.context.scene
    cam = link(bpy.data.objects.new("Camera", bpy.data.cameras.new("Camera")))
    cam.data.clip_end = 5000
    cam.data.sensor_width = 36
    target = link(bpy.data.objects.new("Camera target", None))
    track = cam.constraints.new("TRACK_TO")
    track.target = target
    track.track_axis = "TRACK_NEGATIVE_Z"
    track.up_axis = "UP_Y"
    bpy.context.preferences.edit.keyframe_new_interpolation_type = "BEZIER"
    for frame, loc, look, lens in SHOTS:
        cam.location = loc
        cam.keyframe_insert("location", frame=frame)
        target.location = look
        target.keyframe_insert("location", frame=frame)
        cam.data.lens = lens
        cam.data.keyframe_insert("lens", frame=frame)
    scene.camera = cam
    return cam


def animate_lights(stands, spot_energy):
    """Each stand's floodlights snap on at its frame in LIGHTS_ON."""
    bpy.context.preferences.edit.keyframe_new_interpolation_type = "CONSTANT"
    for b, frame in zip(stands, LIGHTS_ON):
        sock = principled(b["flood"]).inputs["Emission Strength"]
        key_constant(sock, "default_value", 1, 0.0)
        key_constant(sock, "default_value", frame, 60.0)
        for light in b["spots"]:
            key_constant(light, "energy", 1, 0.0)
            key_constant(light, "energy", frame, spot_energy)
    # Advertising boards and the blue band come on just after the last bank.
    for name, value in (("Boards", 4.0), ("Blue band", 8.0)):
        sock = principled(bpy.data.materials[name]).inputs["Emission Strength"]
        key_constant(sock, "default_value", 1, 0.0)
        key_constant(sock, "default_value", LIGHTS_ON[-1] + 10, value)
    for b in stands:
        make_constant(b["flood"].node_tree)
        for light in b["spots"]:
            make_constant(light)
    for name in ("Boards", "Blue band"):
        make_constant(bpy.data.materials[name].node_tree)
    bpy.context.preferences.edit.keyframe_new_interpolation_type = "BEZIER"


def setup_render(preview, percent=None, samples=None):
    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = 24 if preview else 96
    scene.cycles.use_adaptive_sampling = True
    scene.cycles.adaptive_threshold = 0.05 if preview else 0.02
    scene.cycles.use_denoising = True
    scene.cycles.max_bounces = 4
    scene.cycles.volume_bounces = 0
    scene.cycles.volume_step_rate = 4.0
    scene.render.resolution_x = 1920
    scene.render.resolution_y = 1080
    scene.render.resolution_percentage = 50 if preview else 100
    scene.render.fps = FPS
    scene.frame_start, scene.frame_end = 1, FRAMES
    scene.render.image_settings.file_format = "PNG"
    scene.view_settings.view_transform = "AgX"
    try:
        scene.view_settings.look = "AgX - Medium High Contrast"
    except TypeError:
        pass
    scene.view_settings.exposure = 0.0
    if percent:
        scene.render.resolution_percentage = percent
    if samples:
        scene.cycles.samples = samples
    setup_glow(scene)


def setup_glow(scene):
    """Compositor bloom so bright floodlights glow like a camera sees them."""
    try:
        tree = bpy.data.node_groups.new("Glow", "CompositorNodeTree")
        tree.interface.new_socket(name="Image", in_out="OUTPUT", socket_type="NodeSocketColor")
        rl = tree.nodes.new("CompositorNodeRLayers")
        glare = tree.nodes.new("CompositorNodeGlare")
        glare.inputs["Type"].default_value = "Bloom"
        glare.inputs["Threshold"].default_value = 4.0
        glare.inputs["Strength"].default_value = 0.3
        glare.inputs["Size"].default_value = 0.7
        out = tree.nodes.new("NodeGroupOutput")
        tree.links.new(rl.outputs["Image"], glare.inputs["Image"])
        tree.links.new(glare.outputs["Image"], out.inputs[0])
        scene.compositing_node_group = tree
        scene.render.use_compositing = True
        scene.render.compositor_device = "CPU"   # no GPU needed
    except Exception as exc:                 # older/newer Blender: skip the glow
        print("Glow skipped:", exc)


