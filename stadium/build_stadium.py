def build(haze=True, spot_energy=7.0e4):
    random.seed(SEED)
    rng = random.Random(SEED)
    clear_scene()
    mats = {
        "grass": grass_material(),
        "line": material("Lines", (0.85, 0.85, 0.85), rough=0.7),
        "net": material("Net", (0.9, 0.9, 0.9), rough=0.8),
        "concrete": material("Concrete", CONCRETE, rough=0.9),
        "concourse": material("Concourse", (0.02, 0.02, 0.025), rough=0.9),
        "fascia": material("Fascia", (0.01, 0.06, 0.30), rough=0.4,
                           emit=(0.15, 0.35, 1.0), strength=0.6),
        "cladding": material("Cladding", CLADDING, rough=0.6, metal=0.3),
        "roof": roof_material(),
        "steel": material("Steel", STEEL_WHITE, rough=0.35, metal=0.8),
        "seat_blue": material("Seat blue", SEAT_BLUE, rough=0.35),
        "seat_white": material("Seat white", SEAT_WHITE, rough=0.35),
        "boards": material("Boards", (0.02, 0.05, 0.2), emit=(0.25, 0.45, 1.0), strength=0.0),
        "band": material("Blue band", (0.02, 0.05, 0.2), emit=(0.10, 0.30, 1.0), strength=0.0),
        "asphalt": material("Asphalt", (0.012, 0.012, 0.014), rough=0.7),
        "streetlight": material("Street light", (1, 1, 1), emit=(1.0, 0.55, 0.2), strength=25.0),
        "city": city_material(),
    }
    build_pitch(mats)
    seat = seat_mesh()
    stands = [build_stand(s, mats, seat) for s in STANDS]
    build_corners(stands, mats)
    build_city(mats, rng)
    build_world(haze)
    build_camera()
    animate_lights(stands, spot_energy)
    total = sum(b["seats"] for b in stands)
    print(f"Built stadium: {total:,} seats")
    return stands


def render_stills(names=None):
    scene = bpy.context.scene
    os.makedirs(RENDERS, exist_ok=True)
    for name, frame in STILLS.items():
        if names and name not in names:
            continue
        scene.frame_set(frame)
        scene.render.filepath = os.path.join(RENDERS, name + ".png")
        bpy.ops.render.render(write_still=True)
        print("Rendered", scene.render.filepath)


def render_animation(start=None, end=None):
    scene = bpy.context.scene
    if start: scene.frame_start = start
    if end: scene.frame_end = end
    scene.render.filepath = os.path.join(RENDERS, "frames", "")
    bpy.ops.render.render(animation=True)


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else sys.argv[1:]
    if os.path.basename(sys.argv[0]).lower().startswith("blender") and "--" not in sys.argv:
        argv = []                                  # run from Blender's text editor
    ap = argparse.ArgumentParser()
    ap.add_argument("--stills", action="store_true")
    ap.add_argument("--only", nargs="*", help="render only these stills")
    ap.add_argument("--anim", action="store_true")
    ap.add_argument("--start", type=int); ap.add_argument("--end", type=int)
    ap.add_argument("--preview", action="store_true", help="fast, low-quality renders")
    ap.add_argument("--percent", type=int, help="render size as %% of 1920x1080")
    ap.add_argument("--samples", type=int, help="Cycles samples per pixel")
    ap.add_argument("--no-haze", action="store_true")
    ap.add_argument("--no-save", action="store_true")
    args = ap.parse_args(argv)

    build(haze=not args.no_haze)
    setup_render(args.preview, args.percent, args.samples)
    if not args.no_save:
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(HERE, "stadium.blend"))
    if args.stills:
        render_stills(args.only)
    if args.anim:
        render_animation(args.start, args.end)


if __name__ == "__main__":
    main()
